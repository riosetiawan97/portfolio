let currentLang = localStorage.getItem("lang") || "id";

function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem("lang", lang);
    document.querySelectorAll("[data-i18n]").forEach((el) => {
        const key = el.getAttribute("data-i18n");
        if (translations[lang] && translations[lang][key]) {
            // Handle formatting preserving
            if (el.tagName.toLowerCase() === "input" || el.tagName.toLowerCase() === "textarea") {
                el.placeholder = translations[lang][key];
            } else {
                el.innerHTML = translations[lang][key];
            }
        }
    });

    // Update CV download link based on language
    document.querySelectorAll('[data-i18n="btn_download_cv"]').forEach(el => {
        if (el.tagName.toLowerCase() === 'a') {
            el.setAttribute('href', lang === 'id' ? 'CV Rio Setiawan (Idn).pdf' : 'CV Rio Setiawan (Eng).pdf');
        }
    });

    // Update classes on lang buttons if they exist
    const idBtn = document.getElementById("lang-id");
    const enBtn = document.getElementById("lang-en");
    if (idBtn && enBtn) {
        if (lang === 'id') {
            idBtn.classList.add("font-bold", "text-primary", "dark:text-white");
            idBtn.classList.remove("text-slate-400");
            enBtn.classList.add("text-slate-400");
            enBtn.classList.remove("font-bold", "text-primary", "dark:text-white");
        } else {
            enBtn.classList.add("font-bold", "text-primary", "dark:text-white");
            enBtn.classList.remove("text-slate-400");
            idBtn.classList.add("text-slate-400");
            idBtn.classList.remove("font-bold", "text-primary", "dark:text-white");
        }
    }
}

document.addEventListener("DOMContentLoaded", () => {
    setLanguage(currentLang);
});

function toggleLanguage() {
    if (currentLang === 'id') setLanguage('en');
    else setLanguage('id');
}
